        "        'random_seed': seed,\n",
        "        'scaler_type': 'standard'\n",
        "    }\n",
        "    if extra_kwargs:\n",
        "        base_kwargs.update(extra_kwargs)\n",
        "\n",
        "    if model_name == 'TFT':\n",
        "        model = TFT(**base_kwargs)\n",
        "    elif model_name == 'NBEATSx':\n",
