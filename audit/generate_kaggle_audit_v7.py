        "# CELL 4: RESTORE BEST WEIGHTS CALLBACK & MODEL FACTORY\n",
        "# ======================================================================================\n",
        "\n",
        "def get_weights_checksum_from_dict(state_dict) -> str:\n",
        "    h = hashlib.md5()\n",
        "    for k, v in sorted(state_dict.items()):\n",
        "        h.update(k.encode('utf-8'))\n",
        "        h.update(v.detach().cpu().numpy().tobytes())\n",
        "    return h.hexdigest()\n",
        "\n",
        "def get_weights_checksum(model) -> str:\n",
        "    return get_weights_checksum_from_dict(model.state_dict())\n",
        "\n",
        "class RestoreBestWeightsCallback(pl.Callback):\n",
        "    def __init__(self):\n",
        "        super().__init__()\n",
        "        self.best_score = None\n",
        "        self.best_step = None\n",
        "        self.best_state_dict = None\n",
        "        self.best_checksum = None\n",
        "        self.actual_final_step = 0\n",
        "        self.stopped_epoch = 0\n",
        "        self.es_triggered = False\n",
        "        self.restored = False\n",
        "        self.history = []\n",
        "\n",
        "    def on_train_batch_end(self, trainer, pl_module, outputs, batch, batch_idx):\n",
        "        self.actual_final_step = trainer.global_step\n",
        "\n",
        "    def on_validation_end(self, trainer, pl_module):\n",
        "        if getattr(trainer, 'sanity_checking', False) or trainer.global_step == 0:\n",
        "            return\n",
        "        val_loss = trainer.callback_metrics.get('ptl/val_loss', None)\n",
        "        if val_loss is not None:\n",
        "            v_val = float(val_loss)\n",
        "            self.history.append((trainer.global_step, v_val))\n",
        "            if self.best_score is None or v_val < self.best_score:\n",
        "                self.best_score = v_val\n",
        "                self.best_step = trainer.global_step\n",
        "                self.best_state_dict = {k: v.detach().cpu().clone() for k, v in pl_module.state_dict().items()}\n",
        "                self.best_checksum = get_weights_checksum_from_dict(self.best_state_dict)\n",
        "\n",
        "    def on_train_end(self, trainer, pl_module):\n",
        "        self.actual_final_step = trainer.global_step\n",
        "        for cb in trainer.callbacks:\n",
        "            if isinstance(cb, EarlyStopping):\n",
        "                self.stopped_epoch = cb.stopped_epoch\n",
        "                self.es_triggered = (cb.stopped_epoch > 0)\n",
        "        if self.best_state_dict is not None:\n",
        "            pl_module.load_state_dict(self.best_state_dict)\n",
        "            self.restored = True\n",
        "\n",
        "def get_model_instance(model_name: str,\n",
        "                       fset_cols: list,\n",
        "                       h: int = 10,\n",
        "                       input_size: int = 50,\n",
